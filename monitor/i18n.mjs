export function normalizeLanguage(value) { return value === 'ko' ? 'ko' : 'en'; }
export function translate(language, key, values = {}) {
  const text = messages[normalizeLanguage(language)][key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
}
export function readLanguage(storage) {
  try { return normalizeLanguage(storage.getItem(STORAGE_KEY)); } catch { return 'en'; }
}
export function saveLanguage(storage, language) {
  const value = normalizeLanguage(language);
  try { storage.setItem(STORAGE_KEY, value); } catch { /* In-memory language still works. */ }
  return value;
}
