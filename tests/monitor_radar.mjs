import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {radarFrame,replayTime} from '../monitor/radar.mjs';
const display=JSON.parse(readFileSync(new URL('../data/radar_display.json',import.meta.url)));
const facilities=JSON.parse(readFileSync(new URL('../data/site_layout.json',import.meta.url))).facilities;
const record={id:'received',source_id:'channel_a',observed_at_ms:30000,available_at_ms:31000,position:[1,2,3]};
const state={at_ms:31000,duration_ms:120000,playing:true,speed:2,sources:[{source_id:'channel_a',status:'online'},{source_id:'channel_b',status:'offline'}],tracks:[{records:[record]}]};
const frame=radarFrame(display,facilities,state,31000);
assert.equal(frame[0].returns.length,1);
assert.deepEqual(frame[0].returns[0].position,[1,2,3]);
assert.equal(frame[1].returns.length,0);
assert.equal(radarFrame(display,facilities,state,33500)[0].returns.length,0);
assert.equal(radarFrame(display,facilities,{...state,at_ms:30000},30000)[0].returns.length,0);
assert.equal(radarFrame(display,facilities,{...state,sources:[]},31000)[0].returns.length,0);
assert.equal(replayTime(state,1000,1100,true),31200);
assert.equal(replayTime(state,1000,5000,true),32000);
assert.equal(replayTime(state,1000,5000,false),31000);
assert.equal(replayTime({...state,playing:false},1000,5000,true),31000);
assert.equal(replayTime({...state,at_ms:119900},1000,5000,true),120000);
assert.equal(radarFrame(display,[],state,31000).length,0);
console.log('PASS: radar received-only returns, delayed arrival, expiry, offline feeds, pause/disconnect and bounded shared-clock interpolation');
